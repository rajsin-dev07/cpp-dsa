#include<iostream>
using namespace std;
int main(){
    int a =10;
    int b =20;
    cout<<(a==b)<<endl; // Here == is a relational or comparison operator
    cout<<(a!=b)<<endl; // Here != is a relational or comparison operator
    cout<<(a>b)<<endl; // Here > is a relational or comparison operator
    cout<<(a<b)<<endl; // Here < is a relational or comparison operator
    cout<<(a>=b)<<endl; // Here >= is a relational or comparison operator
    cout<<(a<=b)<<endl; // Here <= is a relational or comparison operator

    return 0;
}