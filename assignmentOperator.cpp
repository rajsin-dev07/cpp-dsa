#include<iostream>
using namespace std;
int main(){
    int a =10; // This is a simple assignment operator. Here int is a datatype, 'a' is a variable, 10 is value and = is assignment Operator. 
    
    int x=10;
    x+=5; // This is add & assign 

    int y=20;
    y-=10; // This is subtract & assign

    int z=10;
    z*=5; // This is multiply & assign 

    int b=20;
    b/=10; // This is divide & assign
    
    int c=21;
    c%=10; // This is divide & assign

    cout<<a<<endl;
    cout<<x<<endl;
    cout<<y<<endl;
    cout<<z<<endl;
    cout<<b<<endl;
    cout<<c<<endl;

}